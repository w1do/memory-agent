import type { MemoryConfig } from '../project/config.js';

export const QDRANT_IMAGE = 'qdrant/qdrant:v1.19.2';
export const TYPESENSE_IMAGE = 'typesense/typesense:30.2';

/** docker-compose.yml: loopback-only ports, healthchecks, persistent bind volumes, restart policy. */
export function renderCompose(config: MemoryConfig, user?: string): string {
  const userLine = user ? `    user: "${user}"\n` : '';
  return `# Generated by "memory init". Safe to regenerate; data lives in ./data.
name: memory-${config.collection}
services:
  qdrant:
    image: ${QDRANT_IMAGE}
    container_name: memory-${config.collection}-qdrant
${userLine}    restart: unless-stopped
    environment:
      QDRANT__STORAGE__SNAPSHOTS_PATH: /qdrant/storage/snapshots
      QDRANT__STORAGE__TEMP_PATH: /qdrant/storage/tmp
    ports:
      - "127.0.0.1:${config.qdrantPort}:6333"
    volumes:
      - ./data/qdrant:/qdrant/storage
    healthcheck:
      test: ["CMD-SHELL", "bash -c ':> /dev/tcp/127.0.0.1/6333'"]
      interval: 5s
      timeout: 3s
      retries: 20
      start_period: 5s
  typesense:
    image: ${TYPESENSE_IMAGE}
    container_name: memory-${config.collection}-typesense
${userLine}    restart: unless-stopped
    environment:
      TYPESENSE_API_KEY: \${TYPESENSE_API_KEY:?set TYPESENSE_API_KEY in .memory/.env}
      TYPESENSE_DATA_DIR: /data
      TYPESENSE_ENABLE_CORS: "false"
    ports:
      - "127.0.0.1:${config.typesensePort}:8108"
    volumes:
      - ./data/typesense:/data
    healthcheck:
      test: ["CMD", "bash", "-c", "exec 3<>/dev/tcp/127.0.0.1/8108 && printf 'GET /health HTTP/1.0\\r\\n\\r\\n' >&3 && grep -q true <&3"]
      interval: 5s
      timeout: 3s
      retries: 20
      start_period: 5s
`;
}
