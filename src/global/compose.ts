import { QDRANT_IMAGE, TYPESENSE_IMAGE } from '../cli/compose.js';
import type { GlobalEnv } from './env.js';

/** One machine-wide stack: Qdrant and Typesense bound to loopback only, persistent data under the global dir. */
export function renderSharedCompose(env: GlobalEnv, user?: string): string {
  const userLine = user ? `    user: "${user}"\n` : '';
  const qdrantPort = env.QDRANT_PORT ?? '6333';
  const typesensePort = env.TYPESENSE_PORT ?? '8108';
  return `# Generated by "memory service up". Shared by all projects; data lives in ./data.
name: memory-shared
services:
  qdrant:
    image: ${QDRANT_IMAGE}
    container_name: memory-shared-qdrant
${userLine}    restart: unless-stopped
    environment:
      QDRANT__STORAGE__SNAPSHOTS_PATH: /qdrant/storage/snapshots
      QDRANT__STORAGE__TEMP_PATH: /qdrant/storage/tmp
    ports:
      - "127.0.0.1:${qdrantPort}:6333"
    volumes:
      - ./data/qdrant:/qdrant/storage
    healthcheck:
      test: ["CMD-SHELL", "bash -c ':> /dev/tcp/127.0.0.1/6333'"]
      interval: 5s
      timeout: 3s
      retries: 20
      start_period: 5s
  typesense:
    image: ${TYPESENSE_IMAGE}
    container_name: memory-shared-typesense
${userLine}    restart: unless-stopped
    environment:
      TYPESENSE_API_KEY: \${TYPESENSE_API_KEY:?set TYPESENSE_API_KEY in global.env}
      TYPESENSE_DATA_DIR: /data
      TYPESENSE_ENABLE_CORS: "false"
    ports:
      - "127.0.0.1:${typesensePort}:8108"
    volumes:
      - ./data/typesense:/data
    healthcheck:
      test: ["CMD", "bash", "-c", "exec 3<>/dev/tcp/127.0.0.1/8108 && printf 'GET /health HTTP/1.0\\r\\n\\r\\n' >&3 && grep -q true <&3"]
      interval: 5s
      timeout: 3s
      retries: 20
      start_period: 5s
`;
}
